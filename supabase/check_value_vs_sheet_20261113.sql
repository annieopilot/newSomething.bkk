sheet as (
  select legacy_id, min(name) as name, sum(stock) as stock, max(cost) as cost, sum(value) as value
    from sheet_raw group by legacy_id
),
web as (
  select i.legacy_id, v.name, v.current_stock, v.cost_per_unit, greatest(v.stock_value, 0) as value
    from public.v_inventory v join public.items i on i.id = v.id
   where v.is_active
),
cmp as (
  select coalesce(w.name, s.name) as name,
         case when s.legacy_id is null then 'มีแต่ในเว็บ'
              when w.name is null then 'มีแต่ในชีต (หรือถูกปิดใช้งานในเว็บ)'
              else '' end as note,
         w.current_stock as web_stock, s.stock as sheet_stock,
         w.cost_per_unit as web_cost, s.cost as sheet_cost,
         coalesce(w.value, 0) as web_value, coalesce(s.value, 0) as sheet_value
    from web w full join sheet s on s.legacy_id = w.legacy_id
)
select 'รวมทั้งหมด' as สินค้า, '' as หมายเหตุ,
